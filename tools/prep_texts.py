def dump(pdf, out):
    r = PdfReader(str(pdf))
    text = "\n".join((p.extract_text() or "") for p in r.pages)
    out.write_text(text, encoding="utf-8")
    return len(r.pages), len(text)


def main():
    REF.mkdir(parents=True, exist_ok=True)
    CAND.mkdir(parents=True, exist_ok=True)
    for name, pdf in REFS.items():
        n, L = dump(pdf, REF / name)
        print(f"ref  {name}: {n}页 {L}字")
    for subj, rel, label in CANDS:
        pdf = REPO / "materials" / rel
        if not pdf.exists():
            print(f"MISS {rel}")
            continue
        safe = re.sub(r"[^\w一-鿿]+", "_", Path(rel).stem)[:40]
        out = CAND / f"{subj}__{label}__{safe}.txt"
        n, L = dump(pdf, out)
        print(f"cand {out.name}: {n}页 {L}字")


if __name__ == "__main__":
    main()
